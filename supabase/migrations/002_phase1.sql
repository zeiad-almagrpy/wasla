-- audit every admin write that does not already go through an audited function
create or replace function public.audit_admin_write() returns trigger language plpgsql security definer set search_path = public as $$
declare j jsonb;
begin
  if auth.uid() is null then return null; end if;
  j := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  insert into public.admin_audit_log(admin_id, action, target_type, target_id, details)
  values (auth.uid(), lower(tg_op) || '_' || tg_table_name, tg_table_name, coalesce(j->>'id', j->>'key'), j);
  return null;
end $$;
do $$ declare t text; begin
  foreach t in array array['regions','platform_settings','announcements','delivery_zones'] loop
    execute format('drop trigger if exists trg_audit_%1$s on public.%1$I; create trigger trg_audit_%1$s after insert or update or delete on public.%1$I for each row execute function public.audit_admin_write();', t);
  end loop;
end $$;

