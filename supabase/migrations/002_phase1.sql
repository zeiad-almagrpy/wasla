create or replace function public.rate_limit_guard() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return new; end if;
  if tg_table_name = 'request_posts' and (select count(*) from public.request_posts where customer_id = auth.uid() and created_at > now() - interval '1 hour') >= 5 then raise exception 'rate limit'; end if;
  if tg_table_name = 'request_comments' and (select count(*) from public.request_comments where user_id = auth.uid() and created_at > now() - interval '1 hour') >= 30 then raise exception 'rate limit'; end if;
  if tg_table_name = 'support_requests' and (select count(*) from public.support_requests where user_id = auth.uid() and created_at > now() - interval '1 hour') >= 5 then raise exception 'rate limit'; end if;
  return new;
end $$;
