create or replace function public.status_ar(s public.order_status) returns text language sql immutable as $$
  select case s when 'new' then 'جديد' when 'accepted' then 'تم القبول' when 'preparing' then 'قيد التجهيز' when 'ready' then 'جاهز للاستلام'
    when 'with_courier' then 'في الطريق إليك' when 'delivered' then 'تم التسليم' when 'cancelled' then 'ملغي' end $$;

create or replace function public._notify(p_user uuid, p_title text, p_body text, p_order uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_user is null or p_user is not distinct from auth.uid() then return; end if;
  insert into public.notifications(user_id, title, body, order_id) values (p_user, p_title, p_body, p_order);
end $$;
revoke all on function public._notify(uuid,text,text,uuid) from public, anon, authenticated;

-- ============ notifications on every meaningful order event ============
drop trigger if exists trg_notify_order_status on public.orders;
