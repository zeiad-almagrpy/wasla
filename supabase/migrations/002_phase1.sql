create or replace function public.admin_extend_subscription(p_store_id uuid, p_months integer, p_monthly_price numeric)
returns void language plpgsql security definer set search_path = public as $$
declare v_until date;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  if p_months not between 1 and 12 or p_monthly_price is null or p_monthly_price < 0 or p_monthly_price > 100000 then raise exception 'invalid subscription'; end if;
  select (greatest(coalesce(paid_until, current_date), current_date) + (p_months || ' months')::interval)::date into v_until from public.stores where id = p_store_id;
  if v_until is null then raise exception 'store not found'; end if;
  perform set_config('wesla.bypass','1',true);
  update public.stores set subscription_status = 'active', monthly_price = p_monthly_price, paid_until = v_until where id = p_store_id;
  insert into public.subscription_payments(store_id, amount, months, paid_until, created_by) values (p_store_id, p_monthly_price * p_months, p_months, v_until, auth.uid());
  insert into public.admin_audit_log(admin_id, action, target_type, target_id, details)
  values (auth.uid(), 'store_extend', 'store', p_store_id::text, jsonb_build_object('months', p_months, 'monthly_price', p_monthly_price, 'paid_until', v_until));
end $$;

-- ============ scheduled housekeeping (also callable by hand) ============
create or replace function public.expire_stale_orders() returns integer language plpgsql security definer set search_path = public as $$
declare v_min integer := 30; n integer := 0; r record;
begin
  select coalesce(nullif(value,'')::integer, 30) into v_min from public.platform_settings where key = 'new_order_timeout_min';
  v_min := greatest(5, least(coalesce(v_min,30), 1440));
  update public.orders set status = 'cancelled' where status = 'new' and created_at < now() - make_interval(mins => v_min);
  get diagnostics n = row_count;
  for r in select * from public.orders where fee_status = 'countered' and courier_id is not null and status in ('accepted','preparing','ready') and updated_at < now() - interval '15 minutes' for update loop
    insert into public.order_declines(order_id, courier_id) values (r.id, r.courier_id) on conflict do nothing;
    delete from public.order_courier_contacts where order_id = r.id;
    update public.orders set courier_id = null, courier_proposed_fee = null, courier_reply = null, fee_status = 'pending',
           delivery_fee = r.proposed_delivery_fee, total = r.subtotal + r.proposed_delivery_fee where id = r.id;
  end loop;
  return n;
end $$;

create or replace function public.expire_subscriptions() returns void language plpgsql security definer set search_path = public as $$
declare v_days integer := 30;
begin
  select coalesce(nullif(value,'')::integer, 30) into v_days from public.platform_settings where key = 'merchant_trial_days';
  perform set_config('wesla.bypass','1',true);
  update public.stores set subscription_status = 'expired' where subscription_status = 'active' and paid_until is not null and paid_until < current_date;
  update public.stores set subscription_status = 'expired' where subscription_status = 'trial' and trial_started_at is not null and trial_started_at + make_interval(days => coalesce(v_days,30)) < now();
end $$;
revoke all on function public.expire_stale_orders() from public, anon, authenticated;
revoke all on function public.expire_subscriptions() from public, anon, authenticated;

do $$ begin
  create extension if not exists pg_cron;
  perform cron.schedule('wesla-expire-orders', '* * * * *', 'select public.expire_stale_orders()');
  perform cron.schedule('wesla-expire-subs', '10 0 * * *', 'select public.expire_subscriptions()');
exception when others then raise notice 'pg_cron not enabled (Database > Extensions): run expire_stale_orders() / expire_subscriptions() another way. %', sqlerrm; end $$;

