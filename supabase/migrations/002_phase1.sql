           delivery_fee = o.proposed_delivery_fee, total = o.subtotal + o.proposed_delivery_fee where id = o.id;
  end if;
end $$;

-- the courier types the 4-digit code the STORE shows; five wrong tries lock it
drop function if exists public.courier_pickup_order(uuid);
create or replace function public.courier_pickup_order(p_order_id uuid, p_code text)
returns text language plpgsql security definer set search_path = public as $$
declare o public.orders; c public.order_pickup_codes;
begin
  if not public.has_role('courier') or public.is_blocked() then raise exception 'not allowed'; end if;
  select * into o from public.orders where id = p_order_id and courier_id = auth.uid() for update;
  if not found then raise exception 'order not found'; end if;
  if o.fee_status <> 'accepted' or o.status <> 'ready' then raise exception 'invalid transition'; end if;
  if o.payment_status not in ('cod','confirmed') then raise exception 'payment pending'; end if;
  select * into c from public.order_pickup_codes where order_id = o.id for update;
  if not found then raise exception 'invalid transition'; end if;
  if c.attempts >= 5 then return 'locked'; end if;
  if c.code <> btrim(coalesce(p_code,'')) then
    update public.order_pickup_codes set attempts = attempts + 1 where order_id = o.id;
    return 'wrong_code';
  end if;
  update public.orders set status = 'with_courier' where id = o.id;
  return 'ok';
end $$;

