-- Vodafone Cash is a manual transfer: buyer sends the reference, the store confirms it received the money
create or replace function public.customer_submit_payment(p_order_id uuid, p_ref text)
returns void language plpgsql security definer set search_path = public as $$
declare o public.orders; v_ref text := btrim(coalesce(p_ref,''));
begin
  if public.is_blocked() then raise exception 'not allowed'; end if;
  select * into o from public.orders where id = p_order_id and customer_id = auth.uid() for update;
  if not found then raise exception 'order not found'; end if;
  if o.payment_method <> 'vodafone_cash' or o.payment_status not in ('awaiting','proof_submitted') or o.status in ('cancelled','delivered') then raise exception 'invalid transition'; end if;
  if char_length(v_ref) not between 3 and 40 then raise exception 'invalid reference'; end if;
  update public.orders set payment_status = 'proof_submitted', payment_ref = v_ref where id = o.id;
end $$;

create or replace function public.merchant_review_payment(p_order_id uuid, p_ok boolean)
returns void language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  if public.is_blocked() then raise exception 'not allowed'; end if;
  select o2.* into o from public.orders o2 join public.stores s on s.id = o2.store_id where o2.id = p_order_id and s.owner_id = auth.uid() for update of o2;
  if not found then raise exception 'order not found'; end if;
  if o.payment_method <> 'vodafone_cash' or o.status = 'cancelled' then raise exception 'invalid transition'; end if;
  if p_ok then
    if o.payment_status not in ('awaiting','proof_submitted') then raise exception 'invalid transition'; end if;
    update public.orders set payment_status = 'confirmed' where id = o.id;
  else
    if o.payment_status <> 'proof_submitted' then raise exception 'invalid transition'; end if;
    update public.orders set payment_status = 'awaiting', payment_ref = null where id = o.id;
  end if;
end $$;

-- admin tools for stuck orders (all audited)
create or replace function public.admin_order_action(p_order_id uuid, p_action text, p_note text default '')
returns void language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  select * into o from public.orders where id = p_order_id for update;
  if not found then raise exception 'order not found'; end if;
  if p_action = 'cancel' then
    if o.status in ('delivered','cancelled') then raise exception 'invalid transition'; end if;
    update public.orders set status = 'cancelled', courier_lat = null, courier_lng = null where id = o.id;
  elsif p_action = 'release_courier' then
    if o.courier_id is null or o.status in ('delivered','cancelled') then raise exception 'invalid transition'; end if;
    insert into public.order_declines(order_id, courier_id) values (o.id, o.courier_id) on conflict do nothing;
    delete from public.order_courier_contacts where order_id = o.id;
    update public.orders set courier_id = null, courier_proposed_fee = null, courier_reply = null, courier_lat = null, courier_lng = null,
           status = case when o.status = 'with_courier' then 'ready'::public.order_status else o.status end,
           fee_status = case when o.fee_fixed then 'accepted' else 'pending' end,
           delivery_fee = o.proposed_delivery_fee, total = o.subtotal + o.proposed_delivery_fee where id = o.id;
  elsif p_action = 'force_deliver' then
    if o.status <> 'with_courier' then raise exception 'invalid transition'; end if;
    update public.orders set status = 'delivered', courier_lat = null, courier_lng = null where id = o.id;
  else raise exception 'invalid action'; end if;
  insert into public.admin_audit_log(admin_id, action, target_type, target_id, details)
  values (auth.uid(), 'order_' || p_action, 'order', p_order_id::text, jsonb_build_object('note', left(coalesce(p_note,''), 300), 'status_before', o.status));
end $$;

